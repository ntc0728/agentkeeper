let current = 'en';

function detect() {
  const stored = localStorage.getItem('ak.lang');
  if (stored && STRINGS[stored]) return stored;
  if (stored === 'auto') return systemLang();
  return systemLang();
}

function systemLang() {
  const nav = (navigator.language || 'en').toLowerCase();
  return nav.startsWith('zh') ? 'zh' : 'en';
}

/** Set language. Pass 'auto' to follow the OS. */
function setLang(lang) {
  current = lang === 'auto' ? systemLang() : (STRINGS[lang] ? lang : 'en');
  localStorage.setItem('ak.lang', lang);
  try { document.documentElement.lang = current; } catch (e) { /* not critical */ }
  notify();
  return current;
}

/**
 * Translate. Unknown keys return the key so gaps are obvious, not blank.
 *
 * NOTE: deliberately NOT a top-level `function t` — classic <script> files
 * share one global lexical scope, so a `function t` here would collide with
 * app.js's `const t` and blank the entire window. Everything is exposed via
 * window.__akI18n instead.
 */
const translate = (key, vars) => {
  let s = (STRINGS[current] && STRINGS[current][key])
    || (STRINGS.en[key])
    || key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
};

const listeners = new Set();
function onChange(fn) { listeners.add(fn); }
function notify() { for (const fn of listeners) { try { fn(current); } catch (e) { /* keep going */ } } }

current = detect();

window.__akI18n = {
  t: translate,
  setLang, onChange,
  get lang() { return current; },
  get available() { return Object.keys(STRINGS); }
};

if (typeof module !== 'undefined' && module.exports) module.exports = window.__akI18n;